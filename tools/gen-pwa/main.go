// gen-pwa writes the generated PWA assets: relay/public/app/words.js and the icons
// (PNG, maskable PNG, SVG favicon) drawn by internal/icon.
// Run from the repo root: go run ./tools/gen-pwa
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	"keygate/internal/icon"
	"keygate/internal/store"
)

const dir = "relay/public/app"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-pwa:", err)
		os.Exit(1)
	}
}

func run() error {
	var b bytes.Buffer
	b.WriteString("// Generated by tools/gen-pwa; do not edit. 256-word fingerprint list (same as internal/store/words.go).\nexport const WORDS = [\n")
	wl := store.WordList()
	for i, w := range wl {
		if i%8 == 0 {
			b.WriteString("  ")
		}
		fmt.Fprintf(&b, "%q,", w)
		if i%8 == 7 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("];\n")
	if err := os.WriteFile(filepath.Join(dir, "words.js"), b.Bytes(), 0o644); err != nil {
		return err
	}
	files := map[string][]byte{
		"icon-192.png": icon.PNG(192, icon.Brand),
		"icon-512.png": icon.PNG(512, icon.Brand),
		// iOS masks the touch icon itself; maskable images are full bleed with the glyph in the safe zone.
		"apple-touch-icon.png":  icon.EncodePNG(icon.Render(180, icon.Brand, icon.Style{Maskable: true})),
		"icon-maskable-512.png": icon.EncodePNG(icon.Render(512, icon.Brand, icon.Style{Maskable: true})),
		"icon.svg":              []byte(icon.SVG(icon.Brand, icon.Style{})),
	}
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
